'use strict';

const fs = require('node:fs');
const path = require('node:path');

const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'public', 'style.css'), 'utf8');

function section(start, end) {
  const from = source.indexOf(start);
  if (from < 0) throw new Error(`Missing portal CSS marker: ${start}`);
  const to = end ? source.indexOf(end, from + start.length) : source.length;
  if (to < 0) throw new Error(`Missing portal CSS end marker: ${end}`);
  return source.slice(from, to).trim();
}

// Base controls are copied from the shared source. Stable comment markers select
// only customer-facing rules, keeping the admin theme out of mobile payloads.
const firstLines = source.split(/\r?\n/).slice(0, 3).join('\n');
const accessibility = [
  'html{text-rendering:optimizeLegibility;-webkit-font-smoothing:antialiased}',
  '.button:active:not(:disabled){transform:translateY(0)}',
  '.button:focus-visible,.icon-button:focus-visible,input:focus-visible,select:focus-visible{outline:3px solid var(--focus);outline-offset:2px}',
  '[aria-busy="true"]{cursor:progress}',
  '@media(prefers-reduced-motion:reduce){*{scroll-behavior:auto!important;animation:none!important;transition:none!important}}'
].join('\n');
const typographyTokens = section('/* Unified typography system', '/* Admin hierarchy */')
  .replace(/\/\*[\s\S]*?\*\//g, '')
  .trim();
const customerTypography = section('/* Customer portal hierarchy */', '/* Dense-module layout corrections');
const runtimeBranding = section('/* Portal editor and runtime branding assets. */', '.portal-editor-layout');

const output = [
  '/* Generated by tools/build-portal-css.js. Edit public/style.css, not this file. */',
  firstLines,
  accessibility,
  section('/* Graphite customer portal', '.admin-page .modal{'),
  typographyTokens,
  customerTypography,
  runtimeBranding,
  section('/* Lite customer portal:', '/* Portal editor theme choices:'),
  section('/* Voucher submission feedback', '.duration-fieldset')
].join('\n\n').replace(/\n{3,}/g, '\n\n').trim() + '\n';

const destination = path.join(root, 'public', 'portal.css');
const existing = fs.existsSync(destination) ? fs.readFileSync(destination, 'utf8') : '';
if (existing !== output) fs.writeFileSync(destination, output);
console.log(`${existing === output ? 'Verified' : 'Built'} public/portal.css (${Buffer.byteLength(output)} bytes)`);
